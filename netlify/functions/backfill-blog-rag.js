/**
 * Backfill RAG chunks for every blog post.
 *
 * Scribe (daily-blog.js) auto-seeds new posts into the RAG knowledge base,
 * but historical posts published before that code existed — or where the
 * inline seed failed — won't have a chunk. Visit this endpoint to scan all
 * blogPosts and create + embed a RAG chunk for any missing ones.
 *
 * Idempotent: posts that already have a chunk titled "Blog: ${title}" are
 * skipped. Safe to run any number of times.
 *
 * GET /.netlify/functions/backfill-blog-rag         → dry run, returns counts
 * POST /.netlify/functions/backfill-blog-rag        → actually backfills
 */

const { embedAndStore } = require('./embed-util');

let admin = null;
let db = null;

function initFirebase() {
  if (db) return true;
  const projectId = process.env.FIREBASE_PROJECT_ID;
  const clientEmail = process.env.FIREBASE_CLIENT_EMAIL;
  const privateKey = process.env.FIREBASE_PRIVATE_KEY;
  if (!projectId || !clientEmail || !privateKey) return false;
  try {
    admin = require('firebase-admin');
    if (!admin.apps.length) {
      admin.initializeApp({
        credential: admin.credential.cert({
          projectId,
          clientEmail,
          privateKey: privateKey.replace(/\\n/g, '\n'),
        }),
      });
    }
    db = admin.firestore();
    return true;
  } catch (err) {
    console.error('[backfill-blog-rag] firebase init failed:', err.message);
    return false;
  }
}

function buildRagContent(post) {
  const dateStr = post.publishedAt?.toDate
    ? post.publishedAt.toDate().toISOString().slice(0, 10)
    : (post.date || 'undated');
  const tags = Array.isArray(post.tags) ? post.tags.join(', ') : '';
  const body = post.content || post.excerpt || '';
  return `Blog Post: "${post.title}" (${dateStr})

${post.excerpt || ''}

${tags ? `Key topics: ${tags}\n\n` : ''}Full content summary:
${body.slice(0, 2000)}`;
}

exports.handler = async (event) => {
  const headers = {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Headers': 'Content-Type, Authorization',
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
  };

  if (event.httpMethod === 'OPTIONS') {
    return { statusCode: 200, headers, body: '' };
  }

  if (!initFirebase()) {
    return {
      statusCode: 500,
      headers,
      body: JSON.stringify({ error: 'Firebase not configured' }),
    };
  }

  const dryRun = event.httpMethod !== 'POST';

  try {
    const postsSnap = await db.collection('blogPosts').get();
    const posts = postsSnap.docs.map((d) => ({ id: d.id, ...d.data() }));

    const ragSnap = await db
      .collection('rag_knowledge_base')
      .where('category', '==', 'blog')
      .get();
    const existingTitles = new Set(
      ragSnap.docs.map((d) => d.data().title).filter(Boolean)
    );

    const missing = posts.filter(
      (p) => p.title && !existingTitles.has(`Blog: ${p.title}`)
    );

    const result = {
      blogPostsTotal: posts.length,
      ragChunksExisting: ragSnap.size,
      missing: missing.length,
      dryRun,
    };

    if (dryRun) {
      result.missingPreview = missing.slice(0, 5).map((p) => p.title);
      return { statusCode: 200, headers, body: JSON.stringify(result, null, 2) };
    }

    let created = 0;
    let embedded = 0;
    const errors = [];

    for (const post of missing) {
      try {
        const ragContent = buildRagContent(post);
        const ragDoc = {
          category: 'blog',
          title: `Blog: ${post.title}`,
          content: ragContent,
          metadata: {
            blogId: post.id,
            slug: post.slug,
            autoGenerated: true,
            backfilled: true,
            blogDate: post.publishedAt?.toDate?.()?.toISOString().slice(0, 10) || null,
          },
          tokenEstimate: Math.ceil(ragContent.length / 4),
          embedding: null,
          embeddedAt: null,
          createdAt: admin.firestore.FieldValue.serverTimestamp(),
          updatedAt: admin.firestore.FieldValue.serverTimestamp(),
        };
        const ragRef = await db.collection('rag_knowledge_base').add(ragDoc);
        created += 1;

        const embedResult = await embedAndStore(db, admin, ragRef.id, ragContent);
        if (embedResult.success) embedded += 1;
        else errors.push(`${post.title}: ${embedResult.error}`);
      } catch (err) {
        errors.push(`${post.title}: ${err.message}`);
      }
    }

    return {
      statusCode: 200,
      headers,
      body: JSON.stringify(
        { ...result, created, embedded, errors },
        null,
        2
      ),
    };
  } catch (err) {
    console.error('[backfill-blog-rag] failed:', err);
    return {
      statusCode: 500,
      headers,
      body: JSON.stringify({ error: err.message }),
    };
  }
};
